# Program to display the number listing pattern

# First sequence: 1 2 3 4 5
for i in range(1, 6):
    print(i, end=" ")
print()

# Second sequence: 2 4 6 8 10
for i in range(1, 6):
    print(i * 2, end=" ")
print()

# Third sequence: 1 2 3 4
for i in range(1, 5):
    print(i, end=" ")
print()

# Fourth sequence: 2 4 6 8
for i in range(1, 5):
    print(i * 2, end=" ")
print()

# Fifth sequence: 1 2 3
for i in range(1, 4):
    print(i, end=" ")
print()

# Sixth sequence: 2 4 6
for i in range(1, 4):
    print(i * 2, end=" ")
print()

# Seventh sequence: 1 2
for i in range(1, 3):
    print(i, end=" ")
print()

# Eighth sequence: 2
print(2)

# Ninth sequence: 1
print(1)

# Ending statement
print("END OF NUMBER LISTING")
